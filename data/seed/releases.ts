function id(slug: string) {
  return `release-${slug}`;
}

function link(releaseId: string, platform: ReleaseLink["platform"], url: string): ReleaseLink {
  const now = new Date().toISOString();
  return {
    id: `${releaseId}-${platform}`,
    releaseId,
    platform,
    url,
    verified: true,
    manualOverride: true,
    firstSeenAt: now,
    lastVerifiedAt: now,
  };
}

